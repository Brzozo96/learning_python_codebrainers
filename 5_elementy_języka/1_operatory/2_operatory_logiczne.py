# not - negacja (zmiana wartości na przeciwną)
# or - alternatywa (przynajmniej jeden True) suma
# and - koniunkcja (oba True) iloczyn logiczny

""" not """

print(True)
print(not True)

""" or """
# przynajmniej jeden jest True to zwraca True
print(False or False)
print(False or True)
print(True or False)
print(True or True)

""" and """
# przynajmniej raz False to całość False
print(False and False)
print(False and True)
print(True and False)
print(True and True)


